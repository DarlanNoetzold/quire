#!/usr/bin/env bash
# Quire 1.24 — single-command installer and launcher.
#
# Local use (inside the repository):   ./install.sh
# Remote use (downloads the release):  QUIRE_VERSION=v1.24 ./install.sh
#
# Variables:
#   QUIRE_DIR      install directory             (default: ~/quire)
#   QUIRE_VERSION  tag to download               (default: v1.24)
#   QUIRE_PORT     HTTP port                     (default: 8000)
#   QUIRE_HOST     listen address                (default: 0.0.0.0)
#   QUIRE_NO_START 1 = install without starting  (default: 0)
#   QUIRE_FORCE    1 = overwrite installation    (default: 0)
#   GITHUB_TOKEN   token for private repository  (optional)
set -euo pipefail

REPO="DarlanNoetzold/quire"
VERSION="${QUIRE_VERSION:-v1.24}"
TARGET="${QUIRE_DIR:-$HOME/quire}"
PORT="${QUIRE_PORT:-8000}"
HOST="${QUIRE_HOST:-0.0.0.0}"
NO_START="${QUIRE_NO_START:-0}"
FORCE="${QUIRE_FORCE:-0}"

log() { printf '\033[1;36m[quire]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[quire]\033[0m %s\n' "$*" >&2; exit 1; }

command -v python3 >/dev/null 2>&1 || die "python3 not found. Install Python 3.10 or newer."
python3 -c 'import sys; sys.exit(0 if sys.version_info >= (3, 10) else 1)' \
  || die "Python 3.10 or newer is required (found: $(python3 -V 2>&1))."

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [ -f "$SCRIPT_DIR/app/api.py" ]; then
  TARGET="$SCRIPT_DIR"
  log "Installing from the local directory: $TARGET"
elif [ -f "$TARGET/app/api.py" ] && [ "$FORCE" != "1" ]; then
  log "Existing installation found at $TARGET (use QUIRE_FORCE=1 to overwrite)."
else
  command -v curl >/dev/null 2>&1 || die "curl not found."
  [ -e "$TARGET" ] && [ "$FORCE" != "1" ] && [ -n "$(ls -A "$TARGET" 2>/dev/null)" ] \
    && die "$TARGET is not empty. Use QUIRE_FORCE=1 to overwrite or QUIRE_DIR for another path."
  log "Downloading Quire $VERSION from github.com/$REPO ..."
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' EXIT
  auth=()
  [ -n "${GITHUB_TOKEN:-}" ] && auth=(-H "Authorization: token $GITHUB_TOKEN")
  curl -fsSL ${auth[@]+"${auth[@]}"} \
    "https://codeload.github.com/$REPO/tar.gz/refs/tags/$VERSION" -o "$tmp/quire.tar.gz" \
    || die "Failed to download $VERSION. Private repository? Set GITHUB_TOKEN."
  mkdir -p "$tmp/src" "$TARGET"
  tar -xzf "$tmp/quire.tar.gz" -C "$tmp/src" --strip-components=1
  cp -a "$tmp/src/." "$TARGET/"
  log "Source extracted to $TARGET"
fi

cd "$TARGET"
mkdir -p data/pdfs

if [ ! -x .venv/bin/python ]; then
  log "Creating virtual environment (.venv) ..."
  python3 -m venv .venv || die "Failed to create the venv. On Debian/Ubuntu: sudo apt install python3-venv"
fi

log "Installing dependencies ..."
.venv/bin/pip install --quiet --disable-pip-version-check --upgrade pip >/dev/null 2>&1 || true
.venv/bin/pip install --quiet --disable-pip-version-check -r requirements.txt \
  || die "Failed to install dependencies."

cat > "$TARGET/quire" <<'LAUNCHER'
#!/usr/bin/env bash
# Quire — local server control (generated by install.sh).
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PORT="${QUIRE_PORT:-8000}"
HOST="${QUIRE_HOST:-0.0.0.0}"
PID_FILE="$DIR/data/quire.pid"
LOG_FILE="$DIR/data/quire.log"

running() { [ -f "$PID_FILE" ] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; }

case "${1:-start}" in
  start)
    if running; then echo "Quire is already running (pid $(cat "$PID_FILE")) at http://localhost:$PORT"; exit 0; fi
    mkdir -p "$DIR/data"
    cd "$DIR"
    nohup .venv/bin/uvicorn app.api:app --host "$HOST" --port "$PORT" >> "$LOG_FILE" 2>&1 &
    echo $! > "$PID_FILE"
    for _ in $(seq 1 60); do
      if curl -fsS "http://127.0.0.1:$PORT/api/health" >/dev/null 2>&1; then
        echo "Quire started at http://localhost:$PORT (pid $(cat "$PID_FILE"))"; exit 0
      fi
      sleep 1
    done
    echo "Quire did not respond within 60s. See: $LOG_FILE" >&2; exit 1 ;;
  stop)
    if running; then kill "$(cat "$PID_FILE")" && rm -f "$PID_FILE" && echo "Quire stopped."; else echo "Quire is not running."; fi ;;
  restart) "$0" stop; sleep 1; "$0" start ;;
  status)
    if running; then echo "Running (pid $(cat "$PID_FILE")) at http://localhost:$PORT"; else echo "Stopped."; fi ;;
  logs) tail -n "${2:-80}" -f "$LOG_FILE" ;;
  open) command -v xdg-open >/dev/null 2>&1 && xdg-open "http://localhost:$PORT" || echo "http://localhost:$PORT" ;;
  *) echo "Usage: quire {start|stop|restart|status|logs|open}" >&2; exit 2 ;;
esac
LAUNCHER
chmod +x "$TARGET/quire"

if [ -d "$HOME/.local/bin" ] && [ -w "$HOME/.local/bin" ]; then
  ln -sf "$TARGET/quire" "$HOME/.local/bin/quire"
  log "Command 'quire' available in ~/.local/bin (add it to PATH if needed)."
fi

if [ "$NO_START" = "1" ]; then
  log "Installation complete. Start it with: $TARGET/quire start"
  exit 0
fi

"$TARGET/quire" start
log "Interface: http://localhost:$PORT"
log "Stop: $TARGET/quire stop   |   Logs: $TARGET/quire logs"
